def _needs_context(q, turns):
    """짧거나 지시어뿐인 답변이면 직전 문맥을 붙여서 검색해야 함"""
    if not turns: return False
    if len(q.strip()) <= 20: return True
    if any(w in q for w in ("그거", "그건", "아까", "방금", "말한", "네 ", "예 ", "맞아요")): return True
    last_bot = next((t for r, t in reversed(turns) if r == "bot"), "")
    return any(m in last_bot for m in _ASK_MARK)

def _search_query(q, turns):
    """검색용 질의 — 후속 답변이면 최근 고객 발화들과 합쳐서 의미를 복원"""
    if not _needs_context(q, turns): return _expand_models(q)
    prev_user = [t for r, t in turns if r == "user"][-2:]   # 최근 2턴까지 문맥 유지
    base = (" ".join(prev_user) + " " + q).strip() if prev_user else q
    return _expand_models(base)

