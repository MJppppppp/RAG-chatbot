_PRICE_TBD = "정확한 비용은 제품 입고 및 점검 후 확정되어 안내 드리고 있습니다."

def _strip_unapproved_prices(text):
    if not text: return text
    # "sam 7.8" 의 소수점을 문장 끝으로 오인해 문장이 잘리는 것을 막는다
    text = _re.sub(r"(\d)\.(\d)", "\\1\x00\\2", text)
    removed = False; out = []
    for sent in _SENT.findall(text):
        vals = set()
        for a, b in _MONEY.findall(sent):
            vals.add(int(a.replace(",", "")) if a else int(b) * 10000)
        if vals and not vals <= APPROVED_PRICES:
            removed = True; continue        # 미확정 금액이 든 문장은 통째로 제거
        out.append(sent)
    res = _re.sub(r"[ \t]{2,}", " ", "".join(out))
    res = _re.sub(r"\n{3,}", "\n\n", res).strip()
    if removed and _PRICE_TBD not in res:
        res = (res + "\n" + _PRICE_TBD).strip()
    return res.replace("\x00", ".")


