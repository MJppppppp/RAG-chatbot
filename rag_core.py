def _get_session(sid):
    if not sid: return []
    with _slock:
        v = _sessions.get(sid)
        if not v: return []
        if time.time() - v["ts"] > SESSION_TTL:
            _sessions.pop(sid, None); return []
        return list(v["turns"])

def _push_session(sid, role, text):
    if not sid: return
    with _slock:
        v = _sessions.get(sid)
        if not v or time.time() - v["ts"] > SESSION_TTL:
            v = {"turns": [], "ts": time.time()}
        v["turns"].append((role, text))
        v["turns"] = v["turns"][-MAX_TURNS:]
        v["ts"] = time.time()
        _sessions[sid] = v
        if len(_sessions) > 5000:            # 메모리 보호
            for k in [k for k, x in _sessions.items()
                      if time.time() - x["ts"] > SESSION_TTL][:1000]:
                _sessions.pop(k, None)

