def check(name, turns, must, never):
    sid = "g-" + name
    reset_session(sid)
    rep = ""
    for q in turns:
        rep, _ = answer(q, session_id=sid)
    flat = rep.replace("\n", " ")
    ok = True
    why = []
    # 줄바꿈 자체를 검사하는 케이스가 있으므로 원본(rep)도 함께 본다
    if must and "\n" in must:
        flat = rep
    if must and must not in flat:
        ok = False; why.append(f"'{must}' 없음")
    if never and never in flat:
        ok = False; why.append(f"'{never}' 나옴(금지)")
    return ok, why, flat

fails = 0
print("=" * 70)
for name, turns, must, never in CASES:
    try:
        ok, why, flat = check(name, turns, must, never)
    except Exception as e:
        ok, why, flat = False, [f"예외 {type(e).__name__}"], str(e)[:80]
    if ok:
        print(f"  PASS  {name}")
    else:
        fails += 1
        print(f"  FAIL  {name}  ← {', '.join(why)}")
        print(f"        Q: {' → '.join(turns)}")
        print(f"        A: {flat[:160]}")
print("=" * 70)
print(f"  {len(CASES)-fails}/{len(CASES)} 통과" + ("" if fails == 0 else f"  ({fails}건 실패)"))
sys.exit(1 if fails else 0)
